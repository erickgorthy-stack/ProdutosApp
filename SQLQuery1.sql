SELECT
    c.NOME AS NOME_CATEGORIA,
    SUM(p.QUANTIDADE) AS TOTAL_QUANTIDADE
FROM
    PRODUTO p
INNER JOIN
    CATEGORIA c
ON
    c.ID = p.CATEGORIA_ID
GROUP BY
    c.NOME
ORDER BY
    TOTAL_QUANTIDADE
    DESC;
GO

