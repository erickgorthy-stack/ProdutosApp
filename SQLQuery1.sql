SELECT
    c.NOME AS NOME_CATEGORIA,
    AVG(p.PRECO) AS MEDIA_PRECO
FROM
    PRODUTO p
INNER JOIN
    CATEGORIA c
ON
    c.ID = p.CATEGORIA_ID
GROUP BY
    c.NOME
ORDER BY
    MEDIA_PRECO
    DESC;
GO
